package com.rainingtrace.domain.npc

/**
 * NPC 愿意聊的话题。
 *
 * 每个值都要能从玩家消息里的中文关键词命中（见 `RuleBasedNpcMessageParser`），
 * 并且都要有对应的接话台词——否则话题匹配上了却无话可说。
 */
enum class NpcTopic(val label: String) {
    BOOKS("书与阅读"),
    ART("画画"),
    RUNNING("跑步"),
    FOOD("吃与食堂"),
    WEATHER("天气"),
    NIGHT("夜里的事"),
    PLANTS("草木果子"),

    /** 关于他自己：作息、住在哪、在做什么。 */
    SELF("关于他自己"),

    /** 音乐：歌曲、谱子、乐器。 */
    MUSIC("音乐"),

    /** 缝纫：针线、布料、改衣。 */
    SEWING("缝纫"),

    /** 拍照：摄影、照片、暗房。 */
    PHOTO("拍照"),

    /** 机器：仪器、维修、电路。 */
    TECH("机器"),

    /** 运动：球类、比赛、训练。 */
    SPORT("运动"),

    /** 学习：上课、备考、自习。 */
    STUDY("学习"),

    /** 人：社交、社团、传闻。 */
    PEOPLE("人"),

    /** 声音：广播、录音、校园里的响动。 */
    SOUND("声音"),

    /** 雨：下雨天相关。 */
    RAIN("雨"),

    /** 记忆：过去、老照片、自己的往事。 */
    MEMORY("记忆"),

    /** 猫：猫与其他小动物。 */
    CAT("猫"),

    /** 制图：图纸、地图、草稿。 */
    DRAWING("制图"),

    /** 规则：条例、校规、条款。 */
    LAW("规则"),

    /** 钱：物价、工钱、经费。 */
    MONEY("钱"),

    /** 异常：不对劲的事、符号、影子。 */
    ANOMALY("异常"),
}
