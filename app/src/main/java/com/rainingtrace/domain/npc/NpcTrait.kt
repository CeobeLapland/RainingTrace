package com.rainingtrace.domain.npc

/**
 * NPC 性格标签。
 *
 * 它驱动两件事：**语气**（句长、标点、是否追问）与**偏好**（哪些话题会更热情）。
 * 刻意不做"固定口头禅"那种字段——同一句尾出现三次就露馅，是"AI 味"的第一来源。
 */
enum class NpcTrait(val label: String) {
    /** 话多：句子长，会自己接话、追问。 */
    TALKATIVE("话多"),

    /** 话少：短句作答，不主动展开。 */
    TACITURN("话少"),

    /** 热络：主动关心玩家。 */
    WARM("热络"),

    /** 拘谨：客气、有距离。 */
    RESERVED("拘谨"),

    /** 务实：答事不答情。 */
    PRACTICAL("务实"),

    /** 爱形容：多用比喻与感受。 */
    DREAMY("爱形容"),

    /** 好奇：会反问玩家。 */
    CURIOUS("好奇"),

    /** 按点生活：回答作息时更确定。 */
    PUNCTUAL("按点生活"),

    /** 观察力强：会记住玩家的举止与细节。 */
    OBSERVANT("观察力强"),

    /** 认真：一板一眼，不糊弄。 */
    SERIOUS("认真"),

    /** 怯场：人多或生疏时话少、容易退缩。 */
    SHY("怯场"),

    /** 挑剔：对细节有要求，会挑刺。 */
    EXACTING("挑剔"),

    /** 明亮：情绪外放、说话带亮色。 */
    BRIGHT("明亮"),

    /** 嘴碎：话不停，什么都接得上。 */
    CHATTY("嘴碎"),

    /** 倔：认定了就不改口。 */
    STUBBORN("倔"),

    /** 会听：让人愿意跟他说。 */
    LISTENER("会听"),

    /** 锋利：话里有刀子，不绕弯。 */
    SHARP("锋利"),

    /** 讲义气：对朋友够意思。 */
    GENEROUS("讲义气"),

    /** 不歇：精力旺盛，停不下来。 */
    TIRELESS("不歇"),

    /** 稳：沉得住气，情绪起伏小。 */
    STEADY("稳"),

    /** 来路不明：身份可疑，话里有所保留。 */
    MYSTERIOUS("来路不明"),

    /** 忘我：投入起来会忘记周围。 */
    ABSORBED("忘我"),

    /** 讲究：行事有仪式感。 */
    MANNERED("讲究"),

    /** 自得：对自己的判断很自信。 */
    SMUG("自得"),

    /** 慢性子：不急，节奏慢。 */
    GENTLE("慢性子"),

    /** 不起眼：混在人群里看不出来。 */
    PLAIN("不起眼"),
}
