package com.rainingtrace.domain.npc

/**
 * NPC 性格标签。
 *
 * 它驱动两件事：**语气**（句长、标点、是否追问）与**偏好**（哪些话题会更热情）。
 * 刻意不做"固定口头禅"那种字段——同一句尾出现三次就露馅，是"AI 味"的第一来源。
 */
enum class NpcTrait(val label: String) {
    /** 话多：句子长，会自己接话、追问。 */
    TALKATIVE("话多"),

    /** 话少：短句作答，不主动展开。 */
    TACITURN("话少"),

    /** 热络：主动关心玩家。 */
    WARM("热络"),

    /** 拘谨：客气、有距离。 */
    RESERVED("拘谨"),

    /** 务实：答事不答情。 */
    PRACTICAL("务实"),

    /** 爱形容：多用比喻与感受。 */
    DREAMY("爱形容"),

    /** 好奇：会反问玩家。 */
    CURIOUS("好奇"),

    /** 按点生活：回答作息时更确定。 */
    PUNCTUAL("按点生活"),
}
